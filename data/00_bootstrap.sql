-- This is the only demo script that runs as ACCOUNTADMIN. All later writes
-- must pass --role RAI_DEMO_AVIATION_TEMPORAL explicitly.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RAI_DEMO_AVIATION_TEMPORAL
  COMMENT = 'Scoped implementation role for the aviation temporal RAI demo.';

-- Direct user access plus the requested account-role hierarchy. Privileges
-- flow upward: each parent role can operate the demo role and database.
GRANT ROLE RAI_DEMO_AVIATION_TEMPORAL TO USER "piotr.kraus@relational.ai";
GRANT ROLE RAI_DEMO_AVIATION_TEMPORAL TO ROLE RAI_USER;
GRANT ROLE RAI_DEMO_AVIATION_TEMPORAL TO ROLE RAI_DEVELOPER;
GRANT ROLE RAI_DEMO_AVIATION_TEMPORAL TO ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS PK_AVIATION_TEMPORAL
  COMMENT = 'Synthetic aviation temporal demo: fleets, schedules, and actual flights.';
GRANT OWNERSHIP ON DATABASE PK_AVIATION_TEMPORAL
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL COPY CURRENT GRANTS;

-- Snowflake compute and task execution. The role can operate but not resize
-- or drop the shared warehouse.
GRANT USAGE ON WAREHOUSE RAI_XS TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT OPERATE ON WAREHOUSE RAI_XS TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE RAI_DEMO_AVIATION_TEMPORAL;

-- RelationalAI runtime and observability.
GRANT APPLICATION ROLE RELATIONALAI.RAI_USER
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT APPLICATION ROLE RELATIONALAI.OBSERVABILITY_VIEWER
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;

-- Snowflake Intelligence / Cortex Agent stored-procedure runtime.
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT DATABASE ROLE SNOWFLAKE.PYPI_REPOSITORY_USER
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT APPLICATION ROLE SNOWFLAKE.AI_OBSERVABILITY_EVENTS_LOOKUP
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT USAGE ON INTEGRATION S3_RAI_INTERNAL_BUCKET_EGRESS_INTEGRATION
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT USAGE ON DATABASE SNOWFLAKE_INTELLIGENCE
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT USAGE ON SCHEMA SNOWFLAKE_INTELLIGENCE.AGENTS
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;
GRANT CREATE AGENT ON SCHEMA SNOWFLAKE_INTELLIGENCE.AGENTS
  TO ROLE RAI_DEMO_AVIATION_TEMPORAL;

-- Everything below this line runs under the scoped role.
USE ROLE RAI_DEMO_AVIATION_TEMPORAL;
USE WAREHOUSE RAI_XS;
USE DATABASE PK_AVIATION_TEMPORAL;

CREATE SCHEMA IF NOT EXISTS SOURCE
  COMMENT = 'Synthetic tables shaped like the customer source schemas.';
CREATE SCHEMA IF NOT EXISTS MODEL_INPUT
  COMMENT = 'Normalized and temporally coalesced inputs for the RAI ontology.';
CREATE SCHEMA IF NOT EXISTS VALIDATION
  COMMENT = 'Snowflake baselines and deterministic expected answers.';
CREATE SCHEMA IF NOT EXISTS NOTEBOOKS
  COMMENT = 'Snowsight notebook and supporting stage.';
CREATE SCHEMA IF NOT EXISTS RAI_AGENT
  COMMENT = 'RAI Cortex Agent procedures, stage, and deployment metadata.';

SELECT
  CURRENT_ORGANIZATION_NAME() AS organization_name,
  CURRENT_ACCOUNT_NAME() AS account_name,
  CURRENT_ACCOUNT() AS account_locator,
  CURRENT_USER() AS user_name,
  CURRENT_ROLE() AS role_name,
  CURRENT_DATABASE() AS database_name,
  CURRENT_WAREHOUSE() AS warehouse_name;
